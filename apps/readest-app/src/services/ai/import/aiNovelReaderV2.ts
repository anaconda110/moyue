import type { TOCItem } from '@/libs/document';
import { getAnalysisReportId } from '@/services/ai/analysisService';
import { aiStore } from '@/services/ai/storage/aiStore';
import type { AIAnalysisReport } from '@/services/ai/types';

/**
 * Importer for historical ai-novel-reader-v2 chapter summaries.
 *
 * The 2.1 MB export is not bundled with the app; callers supply it through
 * {@link AiNovelReaderV2ImportOptions.dataset} (for example after reading it
 * from the user's data directory). Without a dataset the import is a no-op,
 * so a missing export never blocks loading reports.
 */

export interface AiNovelReaderV2DatasetReport {
  sectionIndex: number;
  chapterTitle: string;
  content: string;
  createdAt: number;
  updatedAt: number;
  sourceChapterIds: string[];
  sourceSummaryIds: string[];
}

export interface AiNovelReaderV2Dataset {
  version: number;
  source: 'ai-novel-reader-v2';
  bookHash: string;
  bookTitle: string;
  authorName: string;
  sectionCount: number;
  tocSignature: Record<string, string>;
  reports: AiNovelReaderV2DatasetReport[];
}

export interface AiNovelReaderV2ImportContext {
  bookHash: string;
  bookTitle: string;
  authorName: string;
  toc: TOCItem[];
}

export interface AnalysisReportImportStore {
  saveAnalysisReportsIfAbsent(
    reports: AIAnalysisReport[],
    options?: { replaceFailed?: boolean },
  ): Promise<AIAnalysisReport[]>;
}

export interface AiNovelReaderV2ImportOptions {
  /** Historical export to import, or null/undefined when it is not installed. */
  dataset?: AiNovelReaderV2Dataset | null;
  /** Durable report store; defaults to the IndexedDB-backed AI store. */
  store?: AnalysisReportImportStore;
}

const IMPORT_MODEL = 'ai-novel-reader-v2 / chapter-summary';
const IMPORT_COVERAGE =
  'Imported from an ai-novel-reader-v2 historical export generated from complete chapter text.';

export function flattenTocForImport(items: TOCItem[] = []): TOCItem[] {
  const flat: TOCItem[] = [];
  const visit = (entries: TOCItem[]) => {
    for (const item of entries) {
      flat.push(item);
      if (item.subitems?.length) visit(item.subitems);
    }
  };
  visit(items);
  return flat;
}

function matchesTarget(
  context: AiNovelReaderV2ImportContext,
  dataset: AiNovelReaderV2Dataset,
): boolean {
  if (
    context.bookHash !== dataset.bookHash ||
    context.bookTitle.trim() !== dataset.bookTitle ||
    context.authorName.trim() !== dataset.authorName
  ) {
    return false;
  }

  const flatToc = flattenTocForImport(context.toc);
  if (flatToc.length !== dataset.sectionCount) return false;

  return Object.entries(dataset.tocSignature).every(([id, label], index) => {
    const item = flatToc[index];
    return item?.id === Number(id) && item.label === label;
  });
}

function toAnalysisReport(
  dataset: AiNovelReaderV2Dataset,
  report: AiNovelReaderV2DatasetReport,
): AIAnalysisReport {
  return {
    id: getAnalysisReportId(dataset.bookHash, 'chapter', report.sectionIndex),
    bookHash: dataset.bookHash,
    bookTitle: dataset.bookTitle,
    kind: 'chapter',
    sectionIndex: report.sectionIndex,
    chapterTitle: report.chapterTitle,
    content: report.content,
    model: IMPORT_MODEL,
    status: 'complete',
    sources: [],
    coverage: IMPORT_COVERAGE,
    createdAt: report.createdAt,
    updatedAt: report.updatedAt,
    importedFrom: 'ai-novel-reader-v2',
    sourceChapterIds: report.sourceChapterIds,
    sourceSummaryIds: report.sourceSummaryIds,
  };
}

/**
 * Imports historical summaries once for the matching edition.
 * Existing reports win, so this never replaces analysis generated by the user.
 * A failed, empty placeholder is safe to fill because it contains no analysis.
 */
export async function importAiNovelReaderV2Reports(
  context: AiNovelReaderV2ImportContext,
  options: AiNovelReaderV2ImportOptions = {},
): Promise<number> {
  const { dataset, store = aiStore } = options;
  if (!dataset || !matchesTarget(context, dataset)) return 0;
  const inserted = await store.saveAnalysisReportsIfAbsent(
    dataset.reports.map((report) => toAnalysisReport(dataset, report)),
    { replaceFailed: true },
  );
  return inserted.length;
}
